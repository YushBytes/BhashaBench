"""Tests for the committed reference scenarios in `scenarios/`.

These files are documentation that executes. They are cited by
`docs/SCENARIO_FORMAT.md` and `scenarios/README.md`, used in the CLI examples,
and are the first thing a new contributor copies - so a schema change that
invalidates one of them has to fail the build rather than quietly leave the
examples wrong.

The bundle under `scenarios/bundles/` is generated by exporting the same
files, so it is also checked for drift: if someone edits a scenario and
forgets to regenerate, that is caught here and not in review.
"""

from __future__ import annotations

from pathlib import Path

import pytest
import yaml

from app.core import languages
from app.schemas.scenario_spec import ScenarioSpec
from app.services.bundle import BUNDLE_FORMAT, build_bundle, parse_bundle
from app.services.scenario_loader import spec_from_file, spec_from_yaml, spec_to_yaml

REPO_ROOT = Path(__file__).resolve().parents[2]
SCENARIO_DIR = REPO_ROOT / "scenarios"
BUNDLE_PATH = SCENARIO_DIR / "bundles" / "indian_language_reference.yaml"

SCENARIO_FILES = sorted(SCENARIO_DIR.glob("*.yaml"))

# Kept in step with the regeneration command documented in scenarios/README.md.
# A mismatch here means the documented command no longer reproduces the
# committed bundle, which is the same defect as the bundle being stale.
SUITE_NAME = "Indian language reference suite"
SUITE_DESCRIPTION = (
    "Six reference scenarios, one per language, covering code-mixing, "
    "audio stress and a monolingual control."
)


def test_the_reference_directory_is_not_empty() -> None:
    """Guard the parametrisation: an empty glob would silently pass everything."""
    assert len(SCENARIO_FILES) >= 6


class TestEveryReferenceScenario:
    """Each file on its own."""

    @pytest.mark.parametrize("path", SCENARIO_FILES, ids=lambda p: p.stem)
    def test_validates(self, path: Path) -> None:
        spec = spec_from_file(path)

        assert spec.name == path.stem or spec.name

    @pytest.mark.parametrize("path", SCENARIO_FILES, ids=lambda p: p.stem)
    def test_round_trips(self, path: Path) -> None:
        """Canonical YAML of a reference file re-validates to the same spec."""
        spec = spec_from_file(path)

        assert spec_from_yaml(spec_to_yaml(spec)) == spec

    @pytest.mark.parametrize("path", SCENARIO_FILES, ids=lambda p: p.stem)
    def test_filename_matches_the_scenario_name(self, path: Path) -> None:
        """Otherwise the docs cite one name and the file is called another."""
        assert spec_from_file(path).name == path.stem

    @pytest.mark.parametrize("path", SCENARIO_FILES, ids=lambda p: p.stem)
    def test_is_tagged(self, path: Path) -> None:
        """The examples are also the filtering examples, so they need tags."""
        assert spec_from_file(path).tags


@pytest.fixture(scope="module")
def specs() -> list[ScenarioSpec]:
    """Every reference scenario, parsed once."""
    return [spec_from_file(path) for path in SCENARIO_FILES]


class TestCoverage:
    """What the set as a whole is supposed to demonstrate."""

    def test_every_language_used_is_supported(self, specs: list[ScenarioSpec]) -> None:
        for spec in specs:
            assert languages.is_supported(spec.language)

    def test_languages_are_distinct(self, specs: list[ScenarioSpec]) -> None:
        """One scenario per language, so the set reads as a survey."""
        used = [spec.language for spec in specs]

        assert len(used) == len(set(used))

    def test_at_least_six_languages_are_represented(self, specs: list[ScenarioSpec]) -> None:
        assert len({spec.language for spec in specs}) >= 6

    def test_code_mixing_is_demonstrated(self, specs: list[ScenarioSpec]) -> None:
        mixing = [spec for spec in specs if spec.code_mixing is not None]

        assert len(mixing) >= 4

    def test_an_asserted_monolingual_control_exists(self, specs: list[ScenarioSpec]) -> None:
        """`expected: false` is the case most likely to rot unnoticed."""
        monolingual = [
            spec for spec in specs if spec.code_mixing is not None and not spec.code_mixing.expected
        ]

        assert monolingual, "no reference scenario asserts a monolingual caller"

    def test_degraded_audio_is_demonstrated(self, specs: list[ScenarioSpec]) -> None:
        assert any(spec.audio.snr_db <= 15 for spec in specs)
        assert any(spec.audio.packet_loss_percent >= 10 for spec in specs)

    def test_non_ascii_content_survives_a_round_trip(self, specs: list[ScenarioSpec]) -> None:
        """Indian-script text must not come back escaped or mangled."""
        with_script = [
            spec
            for spec in specs
            if spec.code_mixing is not None
            and any(not utterance.isascii() for utterance in spec.code_mixing.sample_utterances)
        ]

        assert with_script, "no reference scenario carries native-script text"
        for spec in with_script:
            serialised = spec_to_yaml(spec)
            assert "\\u" not in serialised
            assert spec_from_yaml(serialised) == spec


class TestReferenceBundle:
    """The generated bundle must stay in step with the files it came from."""

    def test_the_bundle_exists(self) -> None:
        assert BUNDLE_PATH.is_file()

    def test_the_bundle_parses(self) -> None:
        parsed = parse_bundle(BUNDLE_PATH.read_text(encoding="utf-8"))

        assert parsed.entry_errors == []
        assert len(parsed.specs) == len(SCENARIO_FILES)

    def test_the_bundle_declares_the_current_format(self) -> None:
        document = yaml.safe_load(BUNDLE_PATH.read_text(encoding="utf-8"))

        assert document["format"] == BUNDLE_FORMAT

    def test_the_bundle_is_not_stale(self) -> None:
        """Regenerating from the committed scenarios must be a no-op.

        Export is deterministic, so any difference means a scenario was edited
        without rebuilding the bundle - and the bundle is what the import
        examples and the round-trip tests use.
        """
        regenerated = build_bundle(
            [spec_from_file(path) for path in SCENARIO_FILES],
            suite_name=SUITE_NAME,
            suite_description=SUITE_DESCRIPTION,
        )

        assert regenerated == BUNDLE_PATH.read_text(encoding="utf-8")

    def test_the_bundle_contains_every_reference_scenario(self) -> None:
        parsed = parse_bundle(BUNDLE_PATH.read_text(encoding="utf-8"))
        names = {spec.name for spec in parsed.specs}

        assert names == {path.stem for path in SCENARIO_FILES}

    def test_the_bundle_carries_no_identifiers(self) -> None:
        """A bundle describes scenarios, not rows; that is what makes it portable.

        Checked against the parsed keys rather than the raw text, because
        `tracking_id` is legitimate scenario content and a substring search for
        `id:` would flag it.
        """
        document = yaml.safe_load(BUNDLE_PATH.read_text(encoding="utf-8"))
        row_fields = {"id", "suite_id", "created_at", "updated_at", "spec_version"}

        assert not row_fields & set(document)
        for entry in document["scenarios"]:
            assert not row_fields & set(entry)
